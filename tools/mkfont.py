def parse(art):
    rows = [r for r in art.strip('\n').split('\n')]
    assert len(rows) == 8, rows
    out = []
    for r in rows:
        assert len(r) == 8, (r, len(r))
        out.append(int(r.replace('.', '0').replace('#', '1'), 2))
    return out


def mirror(g):
    return [int('{:08b}'.format(b)[::-1], 2) for b in g]


def flipv(g):
    return g[::-1]


def build():
    base = [parse(a) for a in BASE]
    glyphs = list(base)
    # mirrored versions of the asymmetric ones give a second, matching half
    for g in base:
        m = mirror(g)
        if m != g:
            glyphs.append(m)
    # a few vertical flips to round the set out
    for g in base:
        f = flipv(g)
        if f not in glyphs:
            glyphs.append(f)
    glyphs = glyphs[:85]
    assert len(glyphs) == 85, len(glyphs)
    return glyphs


def emit(glyphs):
    lines = []
    for i, g in enumerate(glyphs):
        art = ['%s' % ''.join('#' if b & (0x80 >> x) else '.' for x in range(8))
               for b in g]
        lines.append("; %02d   %s" % (i, art[0]))
        for a in art[1:]:
            lines.append(";      %s" % a)
        lines.append("        !byte " + ",".join("$%02x" % b for b in g))
    return "\n".join(lines)


if __name__ == "__main__":
    gl = build()
    open("fontdata.inc", "w").write(emit(gl) + "\n")
    # contact sheet so the set can be eyeballed
    from PIL import Image
    S, COLS = 6, 17
    img = Image.new("RGB", (COLS*9*S, ((len(gl)+COLS-1)//COLS)*9*S), (0, 0, 0))
    px = img.load()
    for i, g in enumerate(gl):
        gx, gy = (i % COLS)*9*S, (i//COLS)*9*S
        for y in range(8):
            for x in range(8):
                if g[y] & (0x80 >> x):
                    for dy in range(S):
                        for dx in range(S):
                            px[gx+x*S+dx, gy+y*S+dy] = (110, 235, 130)
    img.save("fontsheet.png")
    print("85 glyphs -> fontdata.inc, fontsheet.png")
