"""Build a stand-in C64 character ROM (4 KB) so the program can be simulated.

Letters/digits are rendered from DejaVu Sans Mono; the PETSCII graphics are
hand-drawn approximations.  Shapes are only a stand-in - what the preview is
really testing is the dither/colour ramp the program builds on top of them.
"""
from PIL import Image, ImageDraw, ImageFont

FONT = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf", 9)


def render(ch):
    img = Image.new("L", (8, 8), 0)
    d = ImageDraw.Draw(img)
    d.text((0, -1), ch, fill=255, font=FONT)
    rows = []
    for y in range(8):
        b = 0
        for x in range(8):
            if img.getpixel((x, y)) > 90:
                b |= 0x80 >> x
        rows.append(b)
    return rows


def pat(*rows):
    return [int(r.replace('.', '0').replace('#', '1'), 2) for r in rows]


GFX = {
    0x41: pat("...##...", "..####..", ".######.", "########",
              "########", "..#..#..", ".######.", "........"),          # spade
    0x42: pat("...##...", "...##...", "...##...", "...##...",
              "...##...", "...##...", "...##...", "...##..."),          # |
    0x43: pat("........", "########", "########", "........",
              "........", "........", "........", "........"),
    0x44: pat("........", "........", "........", "########",
              "########", "........", "........", "........"),
    0x45: pat("........", "........", "........", "........",
              "........", "########", "########", "........"),
    0x46: pat("##......", "##......", "##......", "##......",
              "##......", "##......", "##......", "##......"),
    0x47: pat("......##", "......##", "......##", "......##",
              "......##", "......##", "......##", "......##"),
    0x48: pat("########", "########", "........", "........",
              "........", "........", "########", "########"),
    0x49: pat("##....##", "##....##", "##....##", "##....##",
              "##....##", "##....##", "##....##", "##....##"),
    0x4A: pat("...##...", "...##...", "...#####", "...#####",
              "........", "........", "........", "........"),
    0x4B: pat("...##...", "...##...", "#####...", "#####...",
              "........", "........", "........", "........"),
    0x4D: pat("...##...", "...##...", "...##...", "...#####",
              "...#####", "........", "........", "........"),
    0x4E: pat("........", "........", "#####...", "#####...",
              "...##...", "...##...", "...##...", "...##..."),
    0x4F: pat("........", "........", "...#####", "...#####",
              "...##...", "...##...", "...##...", "...##..."),
    0x51: pat("........", "..####..", ".######.", "########",
              "########", ".######.", "..####..", "........"),          # dot
    0x53: pat("........", ".##..##.", "########", "########",
              "########", ".######.", "..####..", "...##..."),          # heart
    0x55: pat("...##...", "...##...", "...#####", "...#####",
              "...##...", "...##...", "...##...", "...##..."),
    0x56: pat("##....##", "###..###", ".######.", "..####..",
              "..####..", ".######.", "###..###", "##....##"),          # X
    0x57: pat("..####..", ".##..##.", "##....##", "##....##",
              "##....##", "##....##", ".##..##.", "..####.."),          # O
    0x58: pat("...##...", "..####..", "...##...", ".######.",
              "########", ".######.", "...##...", "..####.."),          # club
    0x5A: pat("...##...", "..####..", ".######.", "########",
              "########", ".######.", "..####..", "...##..."),          # diamond
    0x5B: pat("...##...", "...##...", "...##...", "########",
              "########", "...##...", "...##...", "...##..."),          # +
    0x5E: pat("........", "########", "########", "..##.##.",
              "..##.##.", "..##.##.", "..##.##.", "........"),          # pi
}


def build():
    rom = bytearray(4096)
    # --- set 1 ($D000): upper case, digits, graphics ---
    for i, ch in enumerate("ABCDEFGHIJKLMNOPQRSTUVWXYZ", start=1):
        rom[i*8:i*8+8] = bytes(render(ch))
    for i, ch in enumerate("0123456789", start=0x30):
        rom[i*8:i*8+8] = bytes(render(ch))
    for code, rows in GFX.items():
        rom[code*8:code*8+8] = bytes(rows)
    # --- set 2 ($D800 = offset 2048): lower case ---
    for i, ch in enumerate("abcdefghijklmnopqrstuvwxyz", start=1):
        o = 2048 + i*8
        rom[o:o+8] = bytes(render(ch))
    return bytes(rom)


if __name__ == "__main__":
    open("charrom.bin", "wb").write(build())
    print("charrom.bin written")
